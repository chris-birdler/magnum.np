# The resulting data/loop.dat is evaluated with the standalone companion
# script evaluate_bh_loop.py (numpy only):
#     python evaluate_bh_loop.py data/loop.dat --period <cycle duration in s>
#
# Conventions:
# * All per-phase columns are PHASE-VOLUME averages: magnum.np's ScalarLogger
#   averages tensors over the WHOLE mesh (state.avg), so every filtered field
#   is divided by phi_i = avg(filter_i) here. Sanity check: |J_i| <= mu0*Ms_i
#   at all times, otherwise filters/normalisation are wrong.
# * The demag operator is linear in Ms*m, so the stray field generated by ONE
#   powder alone is obtained EXACTLY by evaluating demag.h with the other
#   phase's magnetisation masked to zero, and
#       h_demag == h_from_L + h_from_S   (up to float round-off).
#   A larger residual means the filters overlap or miss magnetic cells.


