# Phase filters: float indicator fields of shape [nx, ny, nz, 1], 1.0 inside
# the phase, 0.0 elsewhere. Must be disjoint and together cover ALL cells
# with Ms > 0. Example if you have an integer domain field
# (0 = matrix, 1 = large, 2 = small):
#
#     filter_L = state.Constant([0.]); filter_L[domains == 1] = 1.0
#     filter_S = state.Constant([0.]); filter_S[domains == 2] = 1.0

mu0 = constants.mu_0
phi_L = state.avg(filter_L)   # volume fraction of each powder in the mesh
phi_S = state.avg(filter_S)   # (logged as constants, used for normalisation)


def demag_h_partial(state, source_filter):
    """Demag field generated ONLY by the magnetisation inside source_filter.

    Exploits the linearity of the demag convolution in Ms*m: temporarily
    replacing state.m by the masked magnetisation and evaluating demag.h
    yields exactly the stray field of the source phase, everywhere on the
    mesh. Works with DemagField and DemagFieldPBC alike: both read Ms*m
    freshly on every call, and the cached demag tensor N depends only on
    the mesh, not on m. state.m has no special setter (no normalisation),
    so the swap/restore is safe as long as it happens OUTSIDE llg.step.
    Cost: one extra FFT convolution per call. Returns [nx,ny,nz,3] in A/m.
    """
    m_full = state.m
    try:
        state.m = m_full * source_filter   # keep only the source magnetisation
        return demag.h(state)
    finally:
        state.m = m_full                   # restore the original tensor object


# Logger columns (each vector column expands to _x/_y/_z in the file):
#   t             simulation time                                 [s]
#   h_ext         applied field                                   [A/m]
#   phi_L, phi_S  phase volume fractions (constants)              [1]
#   J_L,  J_S     mu0 * <M>_i, phase-averaged polarisation        [T]
#   hd_L, hd_S    <h_demag>_i, full demag field in phase i        [A/m]
#   hL_L          field of powder L averaged over powder L (self) [A/m]
#   hL_S          field of powder L averaged over powder S (cross)[A/m]
#   hS_L          field of powder S averaged over powder L (cross)[A/m]
#   hS_S          field of powder S averaged over powder S (self) [A/m]
#
# The lambdas only slice/average the fields attached to the state in the
# time loop (BLOCK 2), so each demag convolution runs exactly once per row.
logger = ScalarLogger("data/loop.dat", [
    't',
    ('h_ext', lambda s: external.h(s)),
    ('phi_L', lambda s: float(phi_L)),
    ('phi_S', lambda s: float(phi_S)),
    ('J_L',   lambda s: mu0 * s.material["Ms"] * s.m * filter_L / phi_L),
    ('J_S',   lambda s: mu0 * s.material["Ms"] * s.m * filter_S / phi_S),
    ('hd_L',  lambda s: s.h_demag  * filter_L / phi_L),
    ('hd_S',  lambda s: s.h_demag  * filter_S / phi_S),
    ('hL_L',  lambda s: s.h_from_L * filter_L / phi_L),
    ('hL_S',  lambda s: s.h_from_L * filter_S / phi_S),
    ('hS_L',  lambda s: s.h_from_S * filter_L / phi_L),
    ('hS_S',  lambda s: s.h_from_S * filter_S / phi_S),
])


